def is_rtl(lang: str) -> bool:
    """Return True for right-to-left interface languages."""
    return lang in RTL_LANGUAGES


def tr(lang: str, key: str, **kwargs: object) -> str:
    """Translate a key, falling back to Arabic then English, and format placeholders."""
    template = TRANSLATIONS.get(lang, {}).get(key)
    if template is None:
        template = TRANSLATIONS["ar"].get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, ValueError, IndexError):
            return template
    return template


_current_language = "ar"


def set_current_language(lang: str) -> None:
    """Set the process-wide language used by engine and validation messages."""
    global _current_language
    _current_language = lang if lang in SUPPORTED_LANGUAGES else "ar"


def current_language() -> str:
    return _current_language


def msg(key: str, **kwargs: object) -> str:
    """Translate using the process-wide language (for non-UI modules)."""
    return tr(_current_language, key, **kwargs)
