def _test_cases_by_class() -> list:
    """Count the real test methods per class in the shipped suite (no invented numbers)."""
    path = ROOT / "tests" / "test_kurmanji_tts.py"
    if not path.exists():
        return []
    tree = ast.parse(path.read_text(encoding="utf-8"))
    rows = []
    for node in tree.body:
        if not isinstance(node, ast.ClassDef) or not node.name.startswith("Test"):
            continue
        methods = [
            n for n in node.body
            if isinstance(n, ast.FunctionDef) and n.name.startswith("test_")
        ]
        if methods:
            rows.append((node.name, len(methods)))
    return rows


